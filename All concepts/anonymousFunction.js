// Normal Function Declaration
function greet() {
    console.log("Hello ");
}
greet();

// An anonymous function in JavaScript is simply a function without a name.
let a = function(){
    console.log("Hello this is function expression example")
}
a();
// Advantages of anonymous functions in JavaScript:

// Less code – no need to create a separate named function.
// Good for one-time use – useful when a function is needed only once.
// Great for callbacks – commonly used with events, timers, APIs, etc.
// Keeps code together – logic stays where it is being used.
// Useful with array methods – works nicely with map(), filter(), forEach(), etc.

